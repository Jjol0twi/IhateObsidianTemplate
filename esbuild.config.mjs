import esbuild from "esbuild";
import builtins from "builtin-modules";
import { copyFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";

const mode = process.argv[2] === "release" ? "release" : "development";
const watch = process.argv.includes("--watch");
const root = resolve(import.meta.dirname, "..");
const pluginDir = resolve(root, ".obsidian/plugins/ihate-template");
const banner =
  "/* THIS IS A GENERATED/BUNDLED FILE. Edit ihate-template/src/*.ts instead. */";

const context = await esbuild.context({
  banner: {
    js: banner
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: mode === "development" ? "inline" : false,
  treeShaking: true,
  minify: mode === "release",
  drop: mode === "release" ? ["console"] : [],
  outfile: resolve(pluginDir, "main.js"),
  loader: {
    ".md": "text"
  },
  define: {
    BUILD_MODE: JSON.stringify(mode)
  }
});

async function copyStaticFiles() {
  await mkdir(pluginDir, { recursive: true });
  await copyFile("manifest.json", resolve(pluginDir, "manifest.json"));
  await copyFile("styles.css", resolve(pluginDir, "styles.css"));
}

if (watch) {
  await copyStaticFiles();
  await context.watch();
  console.log(`IhateTemplate ${mode} build watching -> ${pluginDir}`);
} else {
  await copyStaticFiles();
  await context.rebuild();
  await context.dispose();
  console.log(`IhateTemplate ${mode} build complete -> ${pluginDir}`);
}
