import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
// IHATE_OUT_DIR must match the folder the release build wrote to.
const bundleDir = process.env.IHATE_OUT_DIR
  ? resolve(process.env.IHATE_OUT_DIR)
  : resolve(root, "../.obsidian/plugins/ihate-template");

const packageJson = await readJson("package.json");
const manifest = await readJson("manifest.json");
const versions = await readJson("versions.json");
const builtManifest = await readJson(resolve(bundleDir, "manifest.json"));

assertEqual(packageJson.version, manifest.version, "package.json and manifest.json versions differ");
assertEqual(
  versions[manifest.version],
  manifest.minAppVersion,
  "versions.json does not map the manifest version to minAppVersion"
);

const builtMain = await readText(resolve(bundleDir, "main.js"));
if (!builtMain.startsWith("/* THIS IS A GENERATED/BUNDLED FILE.")) {
  throw new Error("Release main.js is missing the generated-file banner");
}
for (const disallowed of [
  "console.",
  "Health check",
  "development mode",
  "IhateTemplate unloaded",
  "sourceMappingURL"
]) {
  if (builtMain.includes(disallowed)) {
    throw new Error(`Release bundle contains development artifact: ${disallowed}`);
  }
}

assertEqual(builtManifest.id, manifest.id, "Built manifest id differs from source");
assertEqual(
  builtManifest.version,
  manifest.version,
  "Built manifest version differs from source"
);
assertEqual(
  await readText(resolve(bundleDir, "styles.css")),
  await readText("styles.css"),
  "Built styles.css differs from source"
);

if (manifest.id !== packageJson.name) {
  throw new Error("manifest id and package name should match for this plugin");
}

if (manifest.author.trim().length === 0) {
  throw new Error("manifest author is required before release");
}

console.log(`Release check passed for ${manifest.id}@${manifest.version}`);

async function readJson(path) {
  return JSON.parse(await readText(path));
}

async function readText(path) {
  return readFile(resolve(root, path), "utf8");
}

function assertEqual(actual, expected, message) {
  if (actual !== expected) {
    throw new Error(`${message}: expected ${expected}, got ${actual}`);
  }
}
